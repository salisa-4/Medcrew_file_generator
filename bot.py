async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text(
        "👋 أهلاً بك في بوت MedCrew Generator!\n\n"
        "من فضلك أرسل ملف الـ Excel الذي يحتوي على الأسئلة برابط مستند (.xlsx)."
    )
    return WAITING_FOR_EXCEL

async def handle_excel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    document = update.message.document
    if not document.file_name.endswith('.xlsx'):
        await update.message.reply_text("❌ عذراً، يرجى إرسال ملف Excel بصيغة .xlsx فقط!")
        return WAITING_FOR_EXCEL

    file = await context.bot.get_file(document.file_id)
    file_bytes = await file.download_as_bytearray()

    # حفظ الملف في ذاكرة المحادثة
    context.user_data['excel_data'] = io.BytesIO(file_bytes)

    keyboard = [
        [InlineKeyboardButton("Anatomy 🦴", callback_data="Anatomy")],
        [InlineKeyboardButton("Histology 🔬", callback_data="Histology")],
        [InlineKeyboardButton("Physiology 🧠", callback_data="Physiology")]
    ]
    reply_markup = InlineKeyboardMarkup(keyboard)

    await update.message.reply_text("✅ تم استلام الملف بنجاح!\nاختر المادة الدراسية:", reply_markup=reply_markup)
    return WAITING_FOR_SUBJECT

async def handle_subject(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    context.user_data['subject'] = query.data

    await query.edit_message_text(
        f"تم اختيار المادة: *{query.data}*\n\n"
        "الآن، أرسل اسم المحاضرة وكود الموديول مفصولين بعلامة `-`\n"
        "مثال:\n`02 HEAD AND NECK MCQs - NSS 201`",
        parse_mode="Markdown"
    )
    return WAITING_FOR_DETAILS

async def handle_details(update: Update, context: ContextTypes.DEFAULT_TYPE):
    text = update.message.text
    if '-' not in text:
        await update.message.reply_text("❌ يرجى كتابة البيانات بالشكل الصحيح مفصولة بـ `-`\nمثال: `02 HEAD AND NECK MCQs - NSS 201`")
        return WAITING_FOR_DETAILS

    parts = text.split('-')
    lecture_name = parts[0].strip()
    module_code = parts[1].strip()

    subject = context.user_data['subject']
    excel_bytes = context.user_data['excel_data']

    msg = await update.message.reply_text("⚙️ جاري توليد ملزمة الـ PDF... انتظر لحظات")

    try:
        df = pd.read_excel(excel_bytes)
        theme = THEMES[subject]
        full_title = f"{theme['prefix']} • {lecture_name.upper()}"

        output_buffer = io.BytesIO()
        engine = MedCrewUniversalEngine(output_buffer, theme, full_title, module_code)
        engine.generate(df)
        output_buffer.seek(0)

        file_name = f"MedCrew_{theme['prefix']}_{lecture_name}.pdf"
        await update.message.reply_document(
            document=output_buffer,
            filename=file_name,
            caption=f"🎉 تم توليد الملزمة بنجاح!\n\n📌 المادة: {subject}\n📚 المحاضرة: {lecture_name}\n🏷️ الموديول: {module_code}"
        )
    except Exception as e:
        await update.message.reply_text(f"❌ حدث خطأ أثناء معالجة الملف: {str(e)}")

    return ConversationHandler.END

async def cancel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    await update.message.reply_text("تم إلغاء العملية.")
    return ConversationHandler.END

# تشغيل البوت
app = ApplicationBuilder().token(BOT_TOKEN).build()

conv_handler = ConversationHandler(
    entry_points=[CommandHandler('start', start)],
    states={
        WAITING_FOR_EXCEL: [MessageHandler(filters.Document.ALL, handle_excel)],
        WAITING_FOR_SUBJECT: [CallbackQueryHandler(handle_subject)],
        WAITING_FOR_DETAILS: [MessageHandler(filters.TEXT & ~filters.COMMAND, handle_details)],
    },
    fallbacks=[CommandHandler('cancel', cancel)]
)

app.add_handler(conv_handler)
print("🤖 البوت يعمل الآن... اذهب إلى تيليجرام وجربه!")
app.run_polling()

