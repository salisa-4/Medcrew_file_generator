class MedCrewUniversalEngine:
    def __init__(self, output_buffer, theme, full_header_title, module_code):
        self.buffer = output_buffer
        self.theme = theme
        self.full_title = full_header_title
        self.module_code = module_code
        self.width, self.height = 595.27, 841.89
        self.margin_x, self.top_margin, self.bottom_margin = 33.7, 65, 55
        self.card_gap = 12
        self.c = canvas.Canvas(self.buffer, pagesize=(self.width, self.height))
        self.usable_width = self.width - (2 * self.margin_x) - 30

    def wrap_text(self, text, font_name, font_size, max_width):
        words = str(text).split(' ')
        lines, current_line = [], ""
        for word in words:
            test_line = f"{current_line} {word}".strip()
            if stringWidth(test_line, font_name, font_size) <= max_width:
                current_line = test_line
            else:
                lines.append(current_line)
                current_line = word
        if current_line: lines.append(current_line)
        return lines

    def calculate_card_dimensions(self, row):
        q_lines = self.wrap_text(f"{row['Q.No']}  {row['Question']}", "Helvetica-Bold", 9.5, self.usable_width)
        half_w = (self.usable_width / 2) - 10
        opt_a_h = self.wrap_text(f"A. {row['A']}", "Helvetica", 9, half_w)
        opt_b_h = self.wrap_text(f"B. {row['B']}", "Helvetica", 9, half_w)
        opt_c_h = self.wrap_text(f"C. {row['C']}", "Helvetica", 9, half_w)
        opt_d_h = self.wrap_text(f"D. {row['D']}", "Helvetica", 9, half_w)

        if len(opt_a_h)==1 and len(opt_b_h)==1 and len(opt_c_h)==1 and len(opt_d_h)==1:
            layout = "grid"
            opts_h = 2 * 14 + 10
            options = {"a": opt_a_h[0], "b": opt_b_h[0], "c": opt_c_h[0], "d": opt_d_h[0]}
        else:
            layout = "vertical"
            opt_a = self.wrap_text(f"A. {row['A']}", "Helvetica", 9, self.usable_width)
            opt_b = self.wrap_text(f"B. {row['B']}", "Helvetica", 9, self.usable_width)
            opt_c = self.wrap_text(f"C. {row['C']}", "Helvetica", 9, self.usable_width)
            opt_d = self.wrap_text(f"D. {row['D']}", "Helvetica", 9, self.usable_width)
            opts_h = (len(opt_a) + len(opt_b) + len(opt_c) + len(opt_d)) * 13 + 10
            options = [opt_a, opt_b, opt_c, opt_d]

        exp_lines = self.wrap_text(f"Right answer ({row['Answer']}) ..... {row['Explanation']}", "Helvetica-Bold", 8.5, self.usable_width - 20)
        tot_h = 20 + (len(q_lines) * 13) + opts_h + (len(exp_lines) * 12 + 10)
        return {"total_height": tot_h, "q_lines": q_lines, "layout": layout, "options": options, "exp_lines": exp_lines}

    def draw_header(self):
        try:
            self.c.drawImage(self.theme["bg_image"], 0, 0, width=self.width, height=self.height)
        except:
            pass
        self.c.setFont("Helvetica-Bold", 15)
        self.c.setFillColor(colors.white)
        self.c.drawString(20, self.height - 31, self.full_title)
        self.c.setFont("Helvetica", 7)
        self.c.setFillColor(colors.HexColor("#718096"))
        self.c.drawString(self.margin_x, 31, f"CAPITAL NATIONAL UNIVERSITY - {self.module_code.upper()}")

    def draw_card(self, x, y_top, card):
        h = card["total_height"]
        w = self.width - (2 * x)
        y_bottom = y_top - h

        self.c.setStrokeColor(colors.HexColor(self.theme["card_border"]))
        self.c.setLineWidth(1)
        self.c.roundRect(x, y_bottom, w, h, 6, stroke=1, fill=0)
        self.c.setFillColor(colors.HexColor(self.theme["card_accent"]))
        self.c.rect(x, y_bottom, 4, h, stroke=0, fill=1)

        curr_y = y_top - 18
        self.c.setFont("Helvetica-Bold", 9.5)
        self.c.setFillColor(colors.HexColor("#1A202C"))
        for line in card["q_lines"]:
            self.c.drawString(x + 15, curr_y, line)
            curr_y -= 13

        curr_y -= 5
        self.c.setFont("Helvetica", 9)
        self.c.setFillColor(colors.HexColor("#4A5568"))
        if card["layout"] == "grid":
            self.c.drawString(x + 20, curr_y, card["options"]["a"])
            self.c.drawString(x + (w / 2) + 5, curr_y, card["options"]["b"])
            curr_y -= 14
            self.c.drawString(x + 20, curr_y, card["options"]["c"])
            self.c.drawString(x + (w / 2) + 5, curr_y, card["options"]["d"])
        else:
            for opt_lines in card["options"]:
                for line in opt_lines:
                    self.c.drawString(x + 20, curr_y, line)
                    curr_y -= 12
            curr_y -= 2

        exp_h = len(card["exp_lines"]) * 12 + 8
        exp_y = y_bottom + 8
        self.c.setFillColor(colors.HexColor(self.theme["exp_bg"]))
        self.c.roundRect(x + 12, exp_y, w - 25, exp_h, 4, stroke=0, fill=1)
        self.c.setFont("Helvetica-Bold", 8.5)
        self.c.setFillColor(colors.HexColor(self.theme["exp_text"]))
        ey = exp_y + exp_h - 11
        for line in card["exp_lines"]:
            self.c.drawString(x + 20, ey, line)
            ey -= 12

    def generate(self, df):
        curr_y = self.height - self.top_margin
        self.draw_header()
        for _, row in df.iterrows():
            card = self.calculate_card_dimensions(row)
            if (curr_y - card["total_height"]) < self.bottom_margin:
                self.c.showPage()
                self.draw_header()
                curr_y = self.height - self.top_margin
            self.draw_card(self.margin_x, curr_y, card)
            curr_y -= (card["total_height"] + self.card_gap)
        self.c.save()

